<script>
function toggleFaq(button) {
    const item = button.closest('.faq-item');
    const content = item.querySelector('.faq-content');
    const iconSpan = item.querySelector('.faq-icon');
    const icon = iconSpan.querySelector('i');

    const isOpen = !content.classList.contains('hidden');

    // Close all other accordions
    document.querySelectorAll('.faq-item').forEach(other => {
        other.querySelector('.faq-content').classList.add('hidden');
        other.querySelector('.faq-icon i').className = 'fa-solid fa-plus';
        other.querySelector('.faq-icon').className = 'faq-icon w-8 h-8 rounded-xl bg-white/5 flex items-center justify-center shrink-0 text-xs text-[#ff5e14] transition-all duration-300 border border-white/10';
    });

    if (!isOpen) {
        content.classList.remove('hidden');
        icon.className = 'fa-solid fa-minus text-white';
        iconSpan.className = 'faq-icon w-8 h-8 rounded-xl bg-gradient-to-br from-[#ff7a1a] to-[#ff5e14] flex items-center justify-center shrink-0 text-xs shadow-md shadow-[#ff5e14]/30';
    }
}
</script>
