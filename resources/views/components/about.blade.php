<script>
(function() {
    const phasesData = [
        {
            img: "{{ asset('images/about-clean.jpg') }}",
            tag: "STEP 01 • BODY ASSESSMENT",
            deliverable: "Personalized Body Composition & Goal Roadmap",
            timeline: "Included Free"
        },
        {
            img: "{{ asset('images/athlete-weights.jpg') }}",
            tag: "STEP 02 • CUSTOM WORKOUT ROUTINE",
            deliverable: "App-Synced Daily Exercise & Weight Targets",
            timeline: "Weekly Updates"
        },
        {
            img: "{{ asset('images/nutrition-food.jpg') }}",
            tag: "STEP 03 • NUTRITION TARGETS",
            deliverable: "Daily Calorie & Protein Blueprint",
            timeline: "Simple & Flexible"
        },
        {
            img: "{{ asset('images/sauna_spa.jpg') }}",
            tag: "STEP 04 • RECOVERY SUITE",
            deliverable: "Ice Plunge & Finnish Cedar Sauna Access",
            timeline: "Post-Workout"
        }
    ];

    window.selectProtocolPhase = function(index) {
        const item = phasesData[index];
        const previewImg = document.getElementById('protocol-preview-img');
        const previewTag = document.getElementById('preview-tag');
        const previewTimeline = document.getElementById('preview-timeline');
        const previewDeliverable = document.getElementById('preview-deliverable');

        if (previewImg) {
            previewImg.style.opacity = '0';
            setTimeout(() => {
                previewImg.src = item.img;
                previewImg.style.opacity = '1';
            }, 180);
        }

        if (previewTag) previewTag.textContent = item.tag;
        if (previewTimeline) previewTimeline.textContent = item.timeline;
        if (previewDeliverable) previewDeliverable.textContent = item.deliverable;

        for (let i = 0; i < phasesData.length; i++) {
            const card = document.getElementById('phase-card-' + i);
            const num = document.getElementById('phase-num-' + i);

            if (card && num) {
                if (i === index) {
                    card.className = "card-vibrant-active p-6 rounded-3xl cursor-pointer transition-all duration-300 group relative";
                    num.className = "w-12 h-12 rounded-2xl bg-gradient-to-br from-[#ff7a1a] to-[#ff5e14] text-white flex items-center justify-center font-heading font-black text-lg shrink-0 shadow-md shadow-[#ff5e14]/30";
                } else {
                    card.className = "card-vibrant p-6 rounded-3xl cursor-pointer transition-all duration-300 group relative";
                    num.className = "w-12 h-12 rounded-2xl bg-white/[0.06] text-slate-300 border border-white/10 flex items-center justify-center font-heading font-black text-lg shrink-0";
                }
            }
        }
    };
})();
</script>
